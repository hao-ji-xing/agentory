const hdr = `"uuid":"u1","parentUuid":"p0","timestamp":"2026-09-11T05:57:00.123Z","sessionId":"s1","cwd":"/home/alice/code/demo","gitBranch":"main"`

func parse(t *testing.T, line string) ([]model.Message, *model.SessionMeta) {
	t.Helper()
	msgs, meta, err := New().ParseLine([]byte(line))
	if err != nil {
		t.Fatalf("ParseLine: %v", err)
	}
	return msgs, meta
}

type want struct {
	kind model.Kind
	role string
	tool string
	text string
}

func check(t *testing.T, got []model.Message, wants ...want) {
	t.Helper()
	if len(got) != len(wants) {
		t.Fatalf("got %d messages, want %d: %+v", len(got), len(wants), got)
	}
	for i, w := range wants {
		g := got[i]
		if g.Kind != w.kind || g.Role != w.role || g.Tool != w.tool || g.Text != w.text {
			t.Errorf("msg %d = {kind:%q role:%q tool:%q text:%q}, want {kind:%q role:%q tool:%q text:%q}",
				i, g.Kind, g.Role, g.Tool, g.Text, w.kind, w.role, w.tool, w.text)
		}
	}
}

func TestParseRules(t *testing.T) {
	cases := []struct {
		name  string
		line  string
		wants []want
	}{
		{
			name:  "user string content",
			line:  `{"type":"user",` + hdr + `,"promptSource":"typed","message":{"role":"user","content":"why does the lock double count?"}}`,
			wants: []want{{model.KindPrompt, "user", "", "why does the lock double count?"}},
		},
		{
			name:  "user text block array",
			line:  `{"type":"user",` + hdr + `,"message":{"role":"user","content":[{"type":"text","text":"first"},{"type":"text","text":"second"}]}}`,
			wants: []want{{model.KindPrompt, "user", "", "first\nsecond"}},
		},
		{
			name:  "image block becomes marker",
			line:  `{"type":"user",` + hdr + `,"message":{"role":"user","content":[{"type":"image","source":{"type":"base64","data":"AAAA"}},{"type":"text","text":"see screenshot"}]}}`,
			wants: []want{{model.KindPrompt, "user", "", "[image]\nsee screenshot"}},
		},
		{
			name:  "tool_result with string content",
			line:  `{"type":"user",` + hdr + `,"message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"t1","content":"exit status 0"}]},"toolUseResult":{"stdout":"exit status 0"}}`,
			wants: []want{{model.KindToolResult, "user", "", "exit status 0"}},
		},
		{
			name:  "tool_result with nested block array and image",
			line:  `{"type":"user",` + hdr + `,"message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"t1","content":[{"type":"text","text":"line one"},{"type":"image","source":{}},{"type":"text","text":"line two"}]}]},"toolUseResult":"raw"}`,
			wants: []want{{model.KindToolResult, "user", "", "line one\n[image]\nline two"}},
		},
		{
			name:  "tool_result is cleaned too",
			line:  `{"type":"user",` + hdr + `,"message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"t1","content":[{"type":"text","text":"ok\n<system-reminder>\nfile changed on disk\n</system-reminder>"}]}]}}`,
			wants: []want{{model.KindToolResult, "user", "", "ok"}},
		},
		{
			name:  "isMeta is not a prompt",
			line:  `{"type":"user",` + hdr + `,"isMeta":true,"message":{"role":"user","content":"Base directory for this skill: /x"}}`,
			wants: []want{{model.KindMeta, "user", "", "Base directory for this skill: /x"}},
		},
		{
			name:  "isCompactSummary",
			line:  `{"type":"user",` + hdr + `,"isCompactSummary":true,"message":{"role":"user","content":"This session is being continued. Summary: fixed the parser."}}`,
			wants: []want{{model.KindSummary, "user", "", "This session is being continued. Summary: fixed the parser."}},
		},
		{
			name:  "command tags",
			line:  `{"type":"user",` + hdr + `,"message":{"role":"user","content":"<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>src/main.go</command-args>"}}`,
			wants: []want{{model.KindCommand, "user", "", "/review src/main.go"}},
		},
		{
			name:  "command without args",
			line:  `{"type":"user",` + hdr + `,"message":{"role":"user","content":"<command-name>/clear</command-name>\n<command-args></command-args>"}}`,
			wants: []want{{model.KindCommand, "user", "", "/clear"}},
		},
		{
			name:  "strip system-reminder across lines",
			line:  `{"type":"user",` + hdr + `,"message":{"role":"user","content":"<system-reminder>\nnoise one\nnoise two\n</system-reminder>real question<system-reminder>more noise</system-reminder>"}}`,
			wants: []want{{model.KindPrompt, "user", "", "real question"}},
		},
		{
			name:  "strip local-command-caveat",
			line:  `{"type":"user",` + hdr + `,"message":{"role":"user","content":"<local-command-caveat>Caveat: generated by commands\nsecond line</local-command-caveat>keep me"}}`,
			wants: []want{{model.KindPrompt, "user", "", "keep me"}},
		},
		{
			name:  "strip local-command-stdout",
			line:  `{"type":"user",` + hdr + `,"message":{"role":"user","content":"<local-command-stdout>Set model to opus\n</local-command-stdout>"}}`,
			wants: nil, // nothing left after cleaning
		},
		{
			name:  "interrupted is meta",
			line:  `{"type":"user",` + hdr + `,"message":{"role":"user","content":[{"type":"text","text":"[Request interrupted by user]"}]}}`,
			wants: []want{{model.KindMeta, "user", "", "[Request interrupted by user]"}},
		},
		{
			name:  "caveat prefix is meta",
			line:  `{"type":"user",` + hdr + `,"message":{"role":"user","content":"Caveat: The messages below were generated by the user."}}`,
			wants: []want{{model.KindMeta, "user", "", "Caveat: The messages below were generated by the user."}},
		},
		{
			name: "assistant text thinking tool_use",
			line: `{"type":"assistant",` + hdr + `,"message":{"role":"assistant","content":[` +
				`{"type":"thinking","thinking":"consider the lock","signature":"x"},` +
				`{"type":"text","text":"The lock is taken twice."},` +
				`{"type":"tool_use","id":"t1","name":"Bash","input":{"description":"run tests","command":"go test ./...","timeout":60}}]}}`,
			wants: []want{
				{model.KindThink, "assistant", "", "consider the lock"},
				{model.KindReply, "assistant", "", "The lock is taken twice."},
				{model.KindToolUse, "assistant", "Bash", "command=go test ./...\ndescription=run tests\ntimeout=60"},
			},
		},
		{
			name:  "system record uses top-level content",
			line:  `{"type":"system",` + hdr + `,"subtype":"away_summary","content":"User was away; build finished."}`,
			wants: []want{{model.KindSystem, "system", "", "User was away; build finished."}},
		},
		{
			name:  "ignored record types",
			line:  `{"type":"file-history-snapshot","messageId":"m","snapshot":{}}`,
			wants: nil,
		},
		{
			name:  "attachment ignored",
			line:  `{"type":"attachment",` + hdr + `,"attachment":{"type":"file","content":"secret"}}`,
			wants: nil,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			msgs, _ := parse(t, tc.line)
			check(t, msgs, tc.wants...)
		})
	}
}

func TestParseCommonFields(t *testing.T) {
	msgs, _ := parse(t, `{"type":"user",`+hdr+`,"message":{"role":"user","content":"hello"}}`)
	if len(msgs) != 1 {
		t.Fatalf("want 1 message, got %d", len(msgs))
	}
	m := msgs[0]
	wantTime := time.Date(2026, 9, 11, 5, 57, 0, 123e6, time.UTC)
	if m.SessionID != "s1" || m.UUID != "u1" || m.ParentUUID != "p0" ||
		m.CWD != "/home/alice/code/demo" || m.Branch != "main" || !m.Time.Equal(wantTime) {
		t.Errorf("common fields not mapped: %+v", m)
	}
	if m.AgentID != "" {
		t.Errorf("main-session record must have empty AgentID, got %q", m.AgentID)
	}
}

func TestParseSidechain(t *testing.T) {
	line := `{"type":"assistant",` + hdr + `,"isSidechain":true,"agentId":"a42","slug":"Explore","message":{"role":"assistant","content":[{"type":"text","text":"found it"}]}}`
	msgs, _ := parse(t, line)
	if len(msgs) != 1 || msgs[0].AgentID != "a42" || msgs[0].Slug != "Explore" || msgs[0].SessionID != "s1" {
		t.Fatalf("sidechain fields not mapped: %+v", msgs)
	}
	// slug may be null in real data.
	line = strings.Replace(line, `"slug":"Explore"`, `"slug":null`, 1)
	msgs, _ = parse(t, line)
	if len(msgs) != 1 || msgs[0].Slug != "" {
		t.Fatalf("null slug: %+v", msgs)
	}
}

func TestParseTitles(t *testing.T) {
	cases := []struct {
		line string
		want string
		rank int
	}{
		{`{"type":"ai-title","sessionId":"s1","aiTitle":"Fix lock bug"}`, "Fix lock bug", model.TitleRankAuto},
		{`{"type":"agent-name","sessionId":"s1","agentName":"lock work"}`, "lock work", model.TitleRankAuto},
		{`{"type":"custom-title","sessionId":"s1","customTitle":"My title"}`, "My title", model.TitleRankCustom},
	}
	for _, tc := range cases {
		msgs, meta := parse(t, tc.line)
		if len(msgs) != 0 {
			t.Errorf("title lines must not produce messages")
		}
		if meta == nil || meta.SessionID != "s1" || meta.Title != tc.want || meta.TitleRank != tc.rank {
			t.Errorf("%s: got %+v", tc.line, meta)
		}
	}
	if model.TitleRankCustom <= model.TitleRankAuto {
		t.Error("custom titles must outrank generated ones")
	}
}

func TestParseInvalidJSON(t *testing.T) {
	if _, _, err := New().ParseLine([]byte(`{"type":"user",`)); err == nil {
		t.Fatal("want error for truncated JSON")
	}
	if msgs, meta, err := New().ParseLine([]byte("  \n")); err != nil || msgs != nil || meta != nil {
		t.Fatal("blank line must be ignored")
	}
}

func TestParseHugeLine(t *testing.T) {
	big := strings.Repeat("x", 2<<20)
	line := `{"type":"user",` + hdr + `,"message":{"role":"user","content":"needle ` + big + `"}}`
	msgs, _ := parse(t, line)
	if len(msgs) != 1 || len(msgs[0].Text) != len(big)+7 {
		t.Fatalf("huge line not parsed intact")
	}
}

func TestMatchAndProject(t *testing.T) {
	root := filepath.FromSlash("/data/claude/projects")
	s := NewWithRoot(root)
	p := filepath.Join(root, "-home-alice-code-demo", "abc.jsonl")
	sub := filepath.Join(root, "-home-alice-code-demo", "abc", "subagents", "agent-1.jsonl")
	if !s.Match(p) || !s.Match(sub) {
		t.Error("session and sub-agent files must match")
	}
	if s.Match(filepath.Join(root, "x", "abc.meta.json")) || s.Match("/elsewhere/a.jsonl") {
		t.Error("non-jsonl or out-of-root files must not match")
	}
	if got := s.ProjectOf(sub); got != "-home-alice-code-demo" {
		t.Errorf("ProjectOf = %q", got)
	}
}
